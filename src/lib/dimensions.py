"""Dimension loading patterns for the gold layer: SCD Type 1 and SCD Type 2."""
from pyspark.sql import DataFrame, SparkSession
from pyspark.sql import functions as F

_NULL_TOKEN = "<NULL>"                       # so NULL and "" hash differently
_BEGINNING_OF_TIME = "TIMESTAMP'1900-01-01'"  # first version: older facts still match
_END_OF_TIME = "TIMESTAMP'9999-12-31'"        # valid_to of the current version


def run_merge(spark: SparkSession, merge_sql: str) -> int:
    """Execute a MERGE statement and return the number of rows inserted + updated."""
    metrics = spark.sql(merge_sql).first()
    return int(metrics["num_inserted_rows"]) + int(metrics["num_updated_rows"])


def upsert_scd1(source: DataFrame, target_table: str, key: str, attributes: list[str]) -> int:
    """SCD Type 1: insert new business keys and overwrite changed attributes in place.

    The surrogate key is generated by the target table (identity column).
    Rows are updated only when an attribute actually changed (null-safe comparison).

    Returns:
        Rows inserted + updated.
    """
    spark = source.sparkSession
    source.select(key, *attributes).createOrReplaceTempView("_scd1_source")

    changed = " OR ".join(f"NOT (t.{c} <=> s.{c})" for c in attributes)
    updates = ", ".join(f"t.{c} = s.{c}" for c in attributes)
    columns = ", ".join([key, *attributes])
    values = ", ".join(f"s.{c}" for c in [key, *attributes])

    return run_merge(spark, f"""
        MERGE INTO {target_table} AS t
        USING _scd1_source AS s
          ON t.{key} = s.{key}
        WHEN MATCHED AND ({changed}) THEN
          UPDATE SET {updates}, t._updated_at = current_timestamp()
        WHEN NOT MATCHED THEN
          INSERT ({columns}, _updated_at) VALUES ({values}, current_timestamp())
    """)


def apply_scd2(source: DataFrame, target_table: str, key: str,
               tracked: list[str], type1: list[str]) -> int:
    """SCD Type 2 with Type 1 attributes on the current version.

    - New business key: first version, valid from the beginning of time.
    - Change in a tracked attribute: close the current version (valid_to = now,
      is_current = FALSE) and open a new one (valid_from = now).
    - Change only in a type-1 attribute: overwrite the current version in place.

    Technique: changed rows appear twice in the MERGE source. Once with their business
    key (to close the current version) and once with a NULL merge key (which never
    matches, so the new version is inserted).

    Returns:
        Rows inserted + updated.
    """
    spark = source.sparkSession

    # Hash of tracked attributes only: a type-1 change must not open a new version
    row_hash = F.sha2(F.concat_ws("||", *[
        F.coalesce(F.col(c).cast("string"), F.lit(_NULL_TOKEN)) for c in tracked]), 256)
    (source.select(key, *tracked, *type1)
           .withColumn("_row_hash", row_hash)
           .createOrReplaceTempView("_scd2_source"))

    attributes = [key, *tracked, *type1]
    insert_columns = ", ".join(
        [*attributes, "valid_from", "valid_to", "is_current", "_row_hash", "_updated_at"])
    insert_values = ", ".join(
        [*(f"s.{c}" for c in attributes),
         "s._valid_from", _END_OF_TIME, "TRUE", "s._row_hash", "current_timestamp()"])

    type1_clause = ""
    if type1:
        type1_changed = " OR ".join(f"NOT (t.{c} <=> s.{c})" for c in type1)
        type1_updates = ", ".join(f"t.{c} = s.{c}" for c in type1)
        type1_clause = (f"WHEN MATCHED AND ({type1_changed}) THEN "
                        f"UPDATE SET {type1_updates}, t._updated_at = current_timestamp()")

    return run_merge(spark, f"""
        MERGE INTO {target_table} AS t
        USING (
          -- Every source row keyed by business key:
          -- inserts new keys, closes changed versions, applies type-1 updates
          SELECT s.{key} AS _merge_key, s.*,
                 CASE WHEN d.{key} IS NULL THEN {_BEGINNING_OF_TIME}
                      ELSE current_timestamp() END AS _valid_from
          FROM _scd2_source s
          LEFT JOIN {target_table} d
            ON d.{key} = s.{key} AND d.is_current

          UNION ALL

          -- Changed rows again with a NULL merge key: forces the INSERT of the new version
          SELECT NULL AS _merge_key, s.*, current_timestamp() AS _valid_from
          FROM _scd2_source s
          JOIN {target_table} d
            ON d.{key} = s.{key} AND d.is_current
          WHERE d._row_hash <> s._row_hash
        ) AS s
        ON t.{key} = s._merge_key AND t.is_current
        WHEN MATCHED AND t._row_hash <> s._row_hash THEN
          UPDATE SET t.valid_to = current_timestamp(),
                     t.is_current = FALSE,
                     t._updated_at = current_timestamp()
        {type1_clause}
        WHEN NOT MATCHED THEN
          INSERT ({insert_columns}) VALUES ({insert_values})
    """)